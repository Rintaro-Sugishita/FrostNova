        public static bool IsValidSingleAddress(string address)
        {
            try
            {
                ExcelAddress addressObject = new ExcelAddress(address);

                if (addressObject.Start.Row == addressObject.End.Row && addressObject.Start.Column== addressObject.End.Column)
                {
                    return true;
                }
            }
            catch { }
            return false;

