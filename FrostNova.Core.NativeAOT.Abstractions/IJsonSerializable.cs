using System;
using System.Collections.Generic;
using System.Text;
using System.Threading.Tasks;

namespace FrostNova.Core.NativeAOT;

#if NET8_0_OR_GREATER

/// <summary>
/// Provides a contract for types that support JSON serialization and deserialization
/// through generated or custom implementations.
/// </summary>
/// <typeparam name="T">
/// The type that can be serialized to JSON and deserialized from JSON.
/// </typeparam>
/// <remarks>
/// This interface defines static and instance members for converting between
/// JSON representations and strongly typed objects, as well as convenience
/// methods for loading from and saving to files.
/// 
/// Implementations are typically generated by a source generator.
/// </remarks>public
public interface IJsonSerializable<T>
{

    /// <summary>
    /// Deserializes an instance of <typeparamref name="T"/> from a JSON string.
    /// </summary>
    /// <param name="json">The JSON string to deserialize.</param>
    /// <returns>The deserialized object, or <see langword="null"/> if deserialization fails.</returns>
    static abstract T? FromJson(string json);

    /// <summary>
    /// Deserializes an instance of <typeparamref name="T"/> from a JSON string.
    /// </summary>
    /// <param name="json">The JSON string to deserialize.</param>
    /// <returns>The deserialized object, or <see langword="null"/> if deserialization fails.</returns>
    static abstract T? FromJson(ReadOnlySpan<char> json);

    /// <summary>
    /// Deserializes an instance of <typeparamref name="T"/> from a JSON string.
    /// </summary>
    /// <param name="utf8Json">The JSON string to deserialize.</param>
    /// <returns>The deserialized object, or <see langword="null"/> if deserialization fails.</returns>
    static abstract T? FromJson(ReadOnlySpan<byte> utf8Json);

    /// <summary>
    /// Loads and deserializes an instance of <typeparamref name="T"/> from a JSON file.
    /// </summary>
    /// <param name="path">The path to the JSON file.</param>
    /// <returns>The deserialized object, or <see langword="null"/> if loading or deserialization fails.</returns>

    static abstract T? LoadFromFile(string path);

    /// <summary>
    /// Asynchronously loads and deserializes an instance of <typeparamref name="T"/> from a JSON file.
    /// </summary>
    /// <param name="path">The path to the JSON file.</param>
    /// <returns>
    /// A task that represents the asynchronous operation. The task result contains
    /// the deserialized object, or <see langword="null"/> if loading or deserialization fails.
    /// </returns>
    static abstract Task<T?> LoadFromFileAsync(string path);

    /// <summary>
    /// Serializes the current instance to a JSON string.
    /// </summary>
    /// <param name="isIndented">
    /// <see langword="true"/> to format the JSON with indentation; otherwise, <see langword="false"/>.
    /// </param>
    /// <returns>The JSON representation of the current instance.</returns>

    string ToJson(bool isIndented = true);

    /// <summary>
    /// Serializes the current instance and writes it to a JSON file.
    /// </summary>
    /// <param name="path">The destination file path.</param>
    void SaveToFile(string path);


    /// <summary>
    /// Asynchronously serializes the current instance and writes it to a JSON file.
    /// </summary>
    /// <param name="path">The destination file path.</param>
    /// <returns>A task that represents the asynchronous file write operation.</returns>
    Task SaveToFileAsync(string path);
}

#endif
